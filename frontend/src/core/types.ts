/**
 * Per-entry typesetting geometry. Mirrors the fields of the same name on
 * `DataItem` in `models/requests.py`; the ranges live in `fox_reader.typeset`
 * and are echoed by the `MIN_*`/`MAX_*` constants in `core/state.ts`.
 *
 * The two spacings are multipliers, with `null` meaning "leave that logic
 * alone"; the rest are neutral at their defaults, so an entry that never
 * touched them renders exactly as it did before they existed. Spacing and
 * scale take part in the auto font fit; the shift and the angles are applied
 * afterwards, to the lettering alone -- never to the plate behind it.
 */
export interface TextGeometry {
    /** Word gap, as a multiple of the face's own space advance. */
    word_spacing: number | null;
    /** Baseline distance, as a multiple of the natural line advance. */
    line_spacing: number | null;
    font_scale_x: number;
    font_scale_y: number;
    /** Post-fit nudge in image pixels, clamped so the ink stays on the page. */
    shift_x: number;
    shift_y: number;
    /** Post-fit rotation in degrees: X/Y tilt the plane, Z spins it clockwise. */
    angle_x: number;
    angle_y: number;
    angle_z: number;
}

export interface DataItem extends TextGeometry {
    og_text: string;
    text: string;
    fontfile: string;
    text_align: TextAlignment;
    points: [number, number][];
    /** 1 is the bottom layer; items are drawn low to high. */
    layer: number;
    /** `null` on any of these means "detect it from the image". */
    font_size: number | null;
    font_color: string | null;
    stroke_width: number | null;
    stroke_color: string | null;
    bg_mode: BgMode;
    bg_color: string | null;
    clean: CleanOptions | null;
}

