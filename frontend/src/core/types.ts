export interface EventMap {
    "image:loaded": [string];
    /**
     * A *different* page is now on screen.
     *
     * Distinct from `image:loaded`, which also fires when the same page is
     * re-fitted or re-fetched. Listen here for the things that belong to one
     * page and must not follow the reader to the next -- the captured text, its
     * translation, the last region.
     */
    "page:changed": [string];
    "entries:render": [];
    "gallery:navigate": [number];
    /** Translator buttons were added or removed after the initial render. */
    "translators:changed": [];
    /** Strip (webtoon) mode was toggled or reset; reader controls should re-render. */
    "strip:changed": [];
}

