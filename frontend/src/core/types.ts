/** How text is set inside its region. Mirrors `typeset.TEXT_ALIGNMENTS`. */
export type TextAlignment = "left" | "center" | "right";

/** How an entry's region is treated before its text is drawn. */
export type BgMode = "auto" | "color" | "transparent" | "clean";

/** Where text-clean gets the shape it removes. */
export type CleanMethod = "region" | "ppocr" | "textseg";

/**
 * Which tuning controls a clean method actually reads.
 *
 * Sent per method by /api/clean/methods so the panel offers only knobs that do
 * something: `glow` under PaddleOCR would be a lie, since box coverage has no
 * halo to absorb. `fill` and `transport` are not listed -- they belong to the
 * reconstruction stage and apply to every method, `region` included.
 */
export type CleanKnob = "glow" | "speed" | "tta" | "tile";

export interface CleanOptions {
    method: CleanMethod;
    /** One of `fox_reader.clean.INPAINT_METHODS`. */
    fill: string;
    glow: boolean;
    transport: boolean;
    /** A preset in `fox_reader.clean.SPEEDS`: how many forward passes to spend. */
    speed: string;
    /** Flip averaging. Only `best` has any for this to switch off. */
    tta: boolean;
    /** One of `fox_reader.clean.TILE_OVERLAPS`; 0 predicts the crop whole. */
    tile: number;
}

export type TranslatorProvider = "deepl" | "jpdb" | "ml" | "custom";

export type TranslateEndpoint = `/translate/${TranslatorProvider}`;

export type CaptureMode = "rect" | "freeform" | "bubble" | null;

