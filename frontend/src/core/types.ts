/**
 * What one directory is and what we may do with it -- `fsaccess.DirReport`.
 *
 * `writable` is the result of a real create-and-delete probe on the backend, not
 * an `os.access` guess, so it can be shown to the user as fact.
 */
export interface DirReport {
    path: string;
    exists: boolean;
    is_dir: boolean;
    is_file: boolean;
    readable: boolean;
    writable: boolean;
    executable: boolean;
    /** Only filled in for the source; `null` means "not counted". */
    image_count: number | null;
    parent: string;
    parent_exists: boolean;
    parent_writable: boolean;
    /** The first blocking problem, already phrased for display. */
    reason: string;
    can_create: boolean;
    ok_as_source: boolean;
    ok_as_dest: boolean;
}

